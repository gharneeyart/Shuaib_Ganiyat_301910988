DROP VIEW  IF EXISTS v_stock_reconciliation;
DROP VIEW  IF EXISTS v_sale_balances;
DROP TABLE IF EXISTS inventory_movements CASCADE;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS sale_items CASCADE;
DROP TABLE IF EXISTS sales CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE TABLE customers (
    customer_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name     VARCHAR(120) NOT NULL,
    phone             VARCHAR(30) UNIQUE,           
    customer_type     VARCHAR(20) NOT NULL DEFAULT 'retail'
                      CHECK (customer_type IN ('retail', 'wholesale')),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    category_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name     VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name      VARCHAR(150) NOT NULL,
    category_id       BIGINT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    current_price     NUMERIC(12,2) NOT NULL CHECK (current_price >= 0),
    quantity_in_stock INTEGER NOT NULL DEFAULT 0 CHECK (quantity_in_stock >= 0),
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sales (
    sale_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       BIGINT REFERENCES customers(customer_id) ON DELETE RESTRICT, 
    sale_date         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sale_status       VARCHAR(20) NOT NULL DEFAULT 'completed'
                      CHECK (sale_status IN ('completed', 'cancelled')),
    cancelled_at      TIMESTAMPTZ,
    notes             TEXT,
    CONSTRAINT ck_cancel_consistent
        CHECK ((sale_status = 'cancelled') = (cancelled_at IS NOT NULL))
);

CREATE TABLE sale_items (
    sale_item_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id           BIGINT NOT NULL REFERENCES sales(sale_id) ON DELETE RESTRICT,
    product_id        BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    quantity          INTEGER NOT NULL CHECK (quantity > 0),
    unit_price        NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    line_total        NUMERIC(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    CONSTRAINT uq_sale_product UNIQUE (sale_id, product_id)
);

CREATE TABLE payments (
    payment_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id           BIGINT NOT NULL REFERENCES sales(sale_id) ON DELETE RESTRICT,
    amount            NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    payment_method    VARCHAR(20) NOT NULL
                      CHECK (payment_method IN ('cash', 'transfer', 'card')),
    payment_date      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reference         VARCHAR(100)
);

CREATE TABLE inventory_movements (
    movement_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    sale_item_id      BIGINT REFERENCES sale_items(sale_item_id) ON DELETE RESTRICT,
    movement_type     VARCHAR(20) NOT NULL
                      CHECK (movement_type IN ('opening', 'sale', 'restock', 'adjustment', 'return')),
    quantity_change   INTEGER NOT NULL CHECK (quantity_change <> 0),
    movement_date     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    remarks           TEXT,
    CONSTRAINT ck_movement_sign CHECK (
        (movement_type = 'sale'                         AND quantity_change < 0) OR
        (movement_type IN ('opening', 'restock', 'return') AND quantity_change > 0) OR
        (movement_type = 'adjustment')
    ),

    CONSTRAINT ck_movement_link CHECK (
        (movement_type IN ('sale', 'return')) = (sale_item_id IS NOT NULL)
    )
);


CREATE UNIQUE INDEX uq_one_sale_movement_per_item
    ON inventory_movements(sale_item_id) WHERE movement_type = 'sale';

CREATE VIEW v_sale_balances AS
SELECT s.sale_id,
       s.customer_id,
       COALESCE(i.total, 0)                         AS sale_total,
       COALESCE(p.paid, 0)                          AS amount_paid,
       COALESCE(i.total, 0) - COALESCE(p.paid, 0)   AS outstanding
FROM sales s
LEFT JOIN (SELECT sale_id, SUM(line_total) AS total FROM sale_items GROUP BY sale_id) i
       ON i.sale_id = s.sale_id
LEFT JOIN (SELECT sale_id, SUM(amount) AS paid FROM payments GROUP BY sale_id) p
       ON p.sale_id = s.sale_id
WHERE s.sale_status = 'completed';


CREATE VIEW v_stock_reconciliation AS
SELECT pr.product_id,
       pr.product_name,
       pr.quantity_in_stock                               AS counter,
       COALESCE(SUM(m.quantity_change), 0)                AS ledger,
       pr.quantity_in_stock - COALESCE(SUM(m.quantity_change), 0) AS difference
FROM products pr
LEFT JOIN inventory_movements m ON m.product_id = pr.product_id
GROUP BY pr.product_id, pr.product_name, pr.quantity_in_stock;
